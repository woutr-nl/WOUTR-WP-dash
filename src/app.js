import { createHash, createHmac, timingSafeEqual } from 'node:crypto';
import { setTimeout as sleep } from 'node:timers/promises';
import express from 'express';
import cookieSession from 'cookie-session';
import config from './config.js';
import { pool } from './db.js';
import { encrypt, decrypt } from './crypto.js';
import { validateSite, validateDaConnection } from './validate.js';
import { ACTIONS, buildEnvNames, isRollback } from './runs.js';
import { startRun, isBusy, anyBusy, listReleases, testSshConnection } from './runner.js';
import { getKeyInfo, rotateKey, ROTATE_BUSY } from './sshkey.js';
import { createLimiter } from './limiter.js';
import { ensureKeyInstalled, testConnection } from './directadmin.js';

const root = new URL('..', import.meta.url).pathname;

// Columns safe to show; secrets are only exposed as has_* booleans.
const PUBLIC_COLUMNS = `id, client_slug, theme_type, ssh_target, wp_path, site_url, site_title,
  admin_email, admin_user, db_name, db_user, db_host, smtp_host, smtp_port, smtp_encryption,
  smtp_user, smtp_from, smtp_from_name, da_username, da_key_state,
  db_pass_enc IS NOT NULL AS has_db_pass, smtp_pass_enc IS NOT NULL AS has_smtp_pass,
  admin_pass_enc IS NOT NULL AS has_admin_pass`;
// admin_pass is generated by deploy: revealable only, the form never sets it.
const SECRETS = { db_pass: 'db_pass_enc', smtp_pass: 'smtp_pass_enc', admin_pass: 'admin_pass_enc' };
const PLAIN = ['client_slug', 'theme_type', 'ssh_target', 'wp_path', 'site_url', 'site_title',
  'admin_email', 'admin_user', 'db_name', 'db_user', 'db_host', 'smtp_host', 'smtp_port',
  'smtp_encryption', 'smtp_user', 'smtp_from', 'smtp_from_name', 'da_username'];

const sha = (s) => createHash('sha256').update(String(s ?? '')).digest();
const same = (a, b) => timingSafeEqual(sha(a), sha(b));

const limiter = createLimiter();

const SESSION_TTL = 12 * 60 * 60 * 1000;
// Binds a session to the current ADMIN_PASSWORD: changing it logs every session out.
const pwTag = () => createHmac('sha256', config.sessionSecret).update(config.adminPassword).digest('base64url').slice(0, 16);
// Logout revokes every session issued before it (single admin).
// ponytail: in-memory, lost on restart — old cookies then still expire by SESSION_TTL.
let revokedBefore = 0;
const validSession = (s, now = Date.now()) => s?.user === config.adminUser && Number.isFinite(s.iat)
  && s.iat > revokedBefore && now - s.iat < SESSION_TTL && s.pw === pwTag();

export function createApp() {
  const app = express();
  // Rollout's proxy is the one trusted hop: req.ip / req.secure come from its X-Forwarded-* headers.
  app.set('trust proxy', 1);
  app.set('view engine', 'ejs');
  app.set('views', root + 'views');
  app.disable('x-powered-by');
  app.locals.ACTION_LABEL = { deploy: 'Deploy', update: 'Bijwerken', live: 'Live gaan' };
  app.locals.STATUS_LABEL = {
    running: 'Bezig', success: 'Geslaagd', failed: 'Mislukt',
    needs_confirmation: 'Wacht op bevestiging', interrupted: 'Onderbroken',
  };
  // Short Dutch description of what was chosen for a run.
  app.locals.describeOptions = (action, o = {}) => {
    const out = [];
    if (action !== 'live') out.push(`thema ${o.version || 'nieuwste'}${o.rollback?.theme ? ' (terugrol)' : ''}`);
    if (o.parent_version) out.push(`woutr ${o.parent_version}${o.rollback?.parent ? ' (terugrol)' : ''}`);
    if (o.smtp || o.apply_smtp) out.push('SMTP toegepast');
    if (o.overwrite) out.push('--overwrite (bevestigd)');
    if (o.force) out.push('--force (bevestigd)');
    if (o.retry_of) out.push(`na run #${o.retry_of}`);
    return out;
  };
  app.locals.isRollback = isRollback;
  app.locals.fmtDate = (d) => (d ? new Date(d).toLocaleString('nl-NL', { timeZone: 'Europe/Amsterdam', dateStyle: 'short', timeStyle: 'medium' }) : '');

  app.use('/public', express.static(root + 'public'));
  app.use(express.urlencoded({ extended: false }));
  app.use(cookieSession({
    name: 'session',
    keys: [config.sessionSecret],
    httpOnly: true,
    sameSite: 'lax',
    maxAge: SESSION_TTL,
  }));
  app.use((req, res, next) => {
    req.sessionOptions.secure = req.secure;
    res.set('Cache-Control', 'no-store');
    next();
  });
  // CSRF: state-changing requests must come from this origin. Browsers always send
  // Sec-Fetch-Site and/or Origin on POST; requests with neither are not from a browser.
  app.use((req, res, next) => {
    if (req.method !== 'POST') return next();
    const site = req.get('sec-fetch-site');
    const origin = req.get('origin');
    let ok = true;
    if (site) ok = site === 'same-origin' || site === 'none';
    else if (origin) {
      try { ok = new URL(origin).host === req.get('host'); } catch { ok = false; }
    }
    if (!ok) return res.status(403).type('text').send('Verzoek van een andere site geweigerd.');
    next();
  });

  const render = (res, view, locals = {}, status = 200) => {
    res.app.render(view, locals, (err, body) => {
      if (err) return res.req.next(err);
      res.status(status).render('layout', { ...locals, body, loggedIn: validSession(res.req.session) });
    });
  };

  app.get('/login', (req, res) => render(res, 'login', { title: 'Inloggen', error: null, username: '' }));

  app.post('/login', async (req, res) => {
    const ip = req.ip;
    if (limiter.blocked(ip)) {
      return render(res, 'login', { title: 'Inloggen', error: 'Te veel mislukte pogingen, probeer het later opnieuw.', username: '' }, 429);
    }
    const { username = '', password = '' } = req.body ?? {};
    const okUser = same(username, config.adminUser);
    const okPass = same(password, config.adminPassword);
    if (okUser && okPass) {
      limiter.success(ip);
      req.session = { user: config.adminUser, iat: Date.now(), pw: pwTag() };
      return res.redirect('/');
    }
    limiter.fail(ip);
    await sleep(500);
    render(res, 'login', { title: 'Inloggen', error: 'Onjuiste gebruikersnaam of wachtwoord.', username: String(username) }, 401);
  });

  app.use((req, res, next) => {
    if (validSession(req.session)) return next();
    req.session = null;
    res.redirect('/login');
  });

  app.post('/logout', (req, res) => {
    revokedBefore = Date.now();
    req.session = null;
    res.redirect('/login');
  });

  app.get('/', async (req, res) => {
    const { rows } = await pool.query(`SELECT s.*,
        r.id AS last_run_id, r.action AS last_action, r.status AS last_status, r.started_at AS last_started_at
      FROM (SELECT ${PUBLIC_COLUMNS} FROM sites) s
      LEFT JOIN LATERAL (SELECT id, action, status, started_at FROM runs WHERE site_id = s.id ORDER BY id DESC LIMIT 1) r ON true
      ORDER BY s.site_title, s.id`);
    render(res, 'sites', { title: 'Sites', sites: rows, daConfigured: await daConfigured() });
  });

  const formLocals = (site, errors = {}) => ({
    title: site.id ? `${site.site_title} bewerken` : 'Site toevoegen', site, errors,
  });
  const emptySite = { theme_type: 'block', admin_user: 'beheer', db_host: 'localhost' };

  async function loadSite(id) {
    if (!/^\d+$/.test(id)) return null;
    const { rows } = await pool.query(`SELECT ${PUBLIC_COLUMNS} FROM sites WHERE id = $1`, [id]);
    return rows[0] ?? null;
  }

  async function save(req, res, existing) {
    const { values, errors } = validateSite(req.body ?? {}, { hasSmtpPass: existing?.has_smtp_pass });
    // Re-render with what was entered (never the secrets).
    const redisplay = () => render(res, 'site-form', formLocals({
      ...(existing ?? emptySite), ...pick(req.body ?? {}, PLAIN), id: existing?.id,
    }, errors), 422);
    if (Object.keys(errors).length) return redisplay();

    const cols = [...PLAIN];
    const params = PLAIN.map((c) => values[c]);
    for (const [field, column] of Object.entries(SECRETS)) {
      if (values[field] === undefined) continue; // keep stored value
      cols.push(column);
      params.push(values[field] === null ? null : encrypt(values[field], config.encryptionKey));
    }
    let id = existing?.id;
    try {
      if (existing) {
        const set = cols.map((c, i) => `${c} = $${i + 1}`).join(', ');
        await pool.query(`UPDATE sites SET ${set}, updated_at = now() WHERE id = $${cols.length + 1}`, [...params, existing.id]);
      } else {
        const ph = cols.map((_, i) => `$${i + 1}`).join(', ');
        ({ rows: [{ id }] } = await pool.query(`INSERT INTO sites (${cols.join(', ')}) VALUES (${ph}) RETURNING id`, params));
      }
    } catch (e) {
      if (e.code !== '23505') throw e;
      errors.site_url = 'Er bestaat al een site met deze URL.';
      return redisplay();
    }
    // The site is saved; a failed key installation only shows up in its status.
    try {
      const conn = values.da_username && await getDaConnection();
      if (conn) await installForSite(conn, { id, ssh_target: values.ssh_target, da_username: values.da_username }, { retired: false });
      else if (!values.da_username) await pool.query('UPDATE sites SET da_key_state = NULL WHERE id = $1', [id]);
    } catch (e) {
      console.error(`Sleutelinstallatie voor site ${id} mislukt: ${e.message}`);
    }
    res.redirect('/');
  }

  app.get('/sites/new', (req, res) => render(res, 'site-form', formLocals(emptySite)));
  app.post('/sites', (req, res) => save(req, res, null));

  app.get('/sites/:id/edit', async (req, res) => {
    const site = await loadSite(req.params.id);
    if (!site) return notFound(res);
    render(res, 'site-form', formLocals(site));
  });

  app.post('/sites/:id', async (req, res) => {
    const site = await loadSite(req.params.id);
    if (!site) return notFound(res);
    await save(req, res, site);
  });

  app.post('/sites/:id/delete', async (req, res) => {
    if (isBusy(req.params.id)) return res.status(409).type('text').send('Er loopt een run voor deze site; verwijderen kan pas als die klaar is.');
    if (/^\d+$/.test(req.params.id)) await pool.query('DELETE FROM sites WHERE id = $1', [req.params.id]);
    res.redirect('/');
  });

  app.post('/sites/:id/reveal/:field', async (req, res) => {
    const column = Object.hasOwn(SECRETS, req.params.field) && SECRETS[req.params.field];
    if (!column || !/^\d+$/.test(req.params.id)) return res.status(404).json({ error: 'Niet gevonden.' });
    const { rows } = await pool.query(`SELECT ${column} AS enc FROM sites WHERE id = $1`, [req.params.id]);
    if (!rows[0]?.enc) return res.status(404).json({ error: 'Niet gevonden.' });
    try {
      res.json({ value: decrypt(rows[0].enc, config.encryptionKey) });
    } catch {
      res.status(500).json({ error: 'Kan niet ontsleutelen — klopt ENCRYPTION_KEY?' });
    }
  });

  // ---- SSH key ----

  app.get('/ssh-key', async (req, res) => {
    const { rows: daSites } = await pool.query(`SELECT id, site_title, da_username, da_key_state FROM sites
      WHERE da_username IS NOT NULL ORDER BY site_title, id`);
    render(res, 'ssh-key', {
      title: 'SSH-sleutel', key: await getKeyInfo(), envKeyStillSet: config.sshPrivateKey !== null,
      daSites, daConfigured: await daConfigured(),
    });
  });

  app.post('/ssh-key/rotate', async (req, res) => {
    if (anyBusy()) return res.status(409).type('text').send(ROTATE_BUSY);
    try {
      await rotateKey(anyBusy);
    } catch (e) {
      if (e.busy) return res.status(409).type('text').send(e.message);
      throw e;
    }
    // The rotation is committed; install the new key everywhere and drop the previous one.
    try {
      const conn = await getDaConnection();
      if (conn) {
        const { rows } = await pool.query('SELECT id, ssh_target, da_username FROM sites WHERE da_username IS NOT NULL ORDER BY id');
        const keys = await keyArgs(true);
        // ponytail: sequential per account; parallelize if the fleet outgrows this
        for (const [user, sites] of Map.groupBy(rows, (s) => s.da_username)) {
          const result = await ensureKeyInstalled(conn, { user, ...keys });
          for (const site of sites) await recordInstall(site, result);
        }
      }
    } catch (e) {
      console.error(`Sleutels installeren na rotatie mislukt: ${e.message}`);
    }
    res.redirect('/ssh-key');
  });

  const SSH_TEST_MESSAGE = {
    ok: 'Verbinding geslaagd: de sleutel is geaccepteerd.',
    denied: 'De server weigert de sleutel. Voeg de publieke sleutel van het dashboard toe aan het hostingaccount (zie de pagina SSH-sleutel).',
    hostkey: 'De hostsleutel van de server is veranderd; SSH weigert te verbinden. Klopt de nieuwe sleutel, verwijder dan de oude regel uit /data/ssh/known_hosts (zie README).',
    unreachable: 'De server is niet bereikbaar (time-out of verbinding geweigerd).',
  };

  async function sshTest(sshTarget) {
    const { outcome, detail } = await testSshConnection(sshTarget);
    let message = SSH_TEST_MESSAGE[outcome];
    if (outcome === 'unreachable' && detail) message += ` (${detail})`;
    return { outcome, message };
  }

  // Not gated on the run lock and never recorded in runs.
  app.post('/sites/:id/test-ssh', async (req, res) => {
    const site = await loadSite(req.params.id);
    if (!site) return res.status(404).json({ error: 'Niet gevonden.' });
    const { outcome, message } = await sshTest(site.ssh_target);
    res.json({ ok: outcome === 'ok', outcome, message });
  });

  // ---- DirectAdmin reseller connection ----

  const daConfigured = async () => (await pool.query('SELECT 1 FROM directadmin')).rowCount > 0;

  async function getDaConnection() {
    const { rows: [row] } = await pool.query('SELECT url, username, password_enc FROM directadmin');
    return row ? { url: row.url, username: row.username, password: decrypt(row.password_enc, config.encryptionKey) } : null;
  }

  async function keyArgs(withRetired) {
    const key = await getKeyInfo();
    return { publicKey: key.public_key, retiredKeys: withRetired ? key.retired.map((r) => r.public_key) : [] };
  }

  // Stores the outcome of ensureKeyInstalled for one site; runs the SSH test after a success.
  async function recordInstall(site, result) {
    const state = { status: result.ok ? 'installed' : 'failed', at: new Date().toISOString() };
    try {
      if (!result.ok) state.error = result.error;
      else {
        if (result.removedOld) state.removed_old = true;
        state.ssh_test = await sshTest(site.ssh_target);
      }
      await pool.query('UPDATE sites SET da_key_state = $2 WHERE id = $1', [site.id, state]);
    } catch (e) {
      console.error(`Sleutelstatus van site ${site.id} opslaan mislukt: ${e.message}`);
    }
    return state;
  }

  async function installForSite(conn, site, { retired }) {
    let result;
    try {
      result = await ensureKeyInstalled(conn, { user: site.da_username, ...await keyArgs(retired) });
    } catch (e) {
      console.error(`Sleutelinstallatie voor site ${site.id} mislukt: ${e.message}`);
      result = { ok: false, error: 'Installatie mislukt door een onverwachte fout.' };
    }
    return recordInstall(site, result);
  }

  const settingsLocals = (conn, extra = {}) => ({ title: 'Instellingen', conn, errors: {}, saved: false, ...extra });

  app.get('/instellingen', async (req, res) => {
    const { rows: [row] } = await pool.query('SELECT url, username FROM directadmin');
    render(res, 'instellingen', settingsLocals(row ? { ...row, has_password: true } : null, { saved: req.query.opgeslagen === '1' }));
  });

  app.post('/instellingen', async (req, res) => {
    const body = req.body ?? {};
    const { rows: [row] } = await pool.query('SELECT url, username FROM directadmin');
    const hasPassword = Boolean(row);
    const { values, errors } = validateDaConnection(body, { hasPassword });
    // The stored secret only ever goes to the panel and user it was entered for.
    if (row && values.password === undefined && (values.url !== row.url || values.username !== row.username))
      errors.password ??= 'Vul het wachtwoord of de login key opnieuw in als je de panel-URL of gebruikersnaam wijzigt.';
    if (Object.keys(errors).length) {
      const str = (k) => (typeof body[k] === 'string' ? body[k] : '');
      return render(res, 'instellingen', settingsLocals({ url: str('url'), username: str('username'), has_password: hasPassword }, { errors }), 422);
    }
    // Without a new secret, URL and username equal the stored row: nothing to write.
    if (values.password !== undefined) {
      await pool.query(`INSERT INTO directadmin (id, url, username, password_enc) VALUES (true, $1, $2, $3)
        ON CONFLICT (id) DO UPDATE SET url = $1, username = $2, password_enc = $3, updated_at = now()`,
      [values.url, values.username, encrypt(values.password, config.encryptionKey)]);
    }
    res.redirect('/instellingen?opgeslagen=1');
  });

  app.post('/instellingen/delete', async (req, res) => {
    await pool.query('DELETE FROM directadmin');
    res.redirect('/instellingen');
  });

  app.post('/instellingen/test', async (req, res) => {
    const conn = await getDaConnection();
    if (!conn) return res.json({ ok: false, message: 'Geen resellerkoppeling ingesteld.' });
    res.json(await testConnection(conn));
  });

  app.post('/sites/:id/install-key', async (req, res) => {
    const site = await loadSite(req.params.id);
    if (!site) return res.status(404).json({ error: 'Niet gevonden.' });
    if (!site.da_username) return res.json({ ok: false, message: 'Geen hosting-account ingevuld bij deze site.' });
    const conn = await getDaConnection();
    if (!conn) return res.json({ ok: false, message: 'Geen resellerkoppeling ingesteld (zie Instellingen).' });
    const state = await installForSite(conn, site, { retired: true });
    const message = state.status === 'installed'
      ? `Sleutel geïnstalleerd${state.removed_old ? ', oude sleutel verwijderd' : ''}. SSH-test: ${state.ssh_test.message}`
      : `Mislukt: ${state.error}`;
    res.json({ ok: state.status === 'installed', message });
  });

  // ---- Runs ----

  const lastRun = async (siteId, actions) => (await pool.query(
    'SELECT * FROM runs WHERE site_id = $1 AND action = ANY($2) ORDER BY id DESC LIMIT 1', [siteId, actions])).rows[0];

  // Versions installed per the last successful deploy/update.
  async function installed(siteId) {
    const { rows } = await pool.query(`SELECT result FROM runs WHERE site_id = $1 AND action IN ('deploy','update')
      AND status = 'success' ORDER BY id DESC LIMIT 1`, [siteId]);
    const r = rows[0]?.result ?? {};
    return { theme: r.theme_version || null, parent: r.parent_version || null };
  }
  const isLive = async (siteId) => (await lastRun(siteId, ['live']))?.status === 'success';
  const unprocessable = (res, msg) => res.status(422).type('text').send(msg);

  app.get('/sites/:id/runs', async (req, res) => {
    const site = await loadSite(req.params.id);
    if (!site) return notFound(res);
    const { rows: runs } = await pool.query(`SELECT id, action, status, options, result, exit_code, started_at, finished_at
      FROM runs WHERE site_id = $1 ORDER BY id DESC`, [site.id]);
    render(res, 'runs', { title: `Runs · ${site.site_title}`, site, runs, live: await isLive(site.id), busy: isBusy(site.id) });
  });

  app.get('/sites/:id/run/:action', async (req, res) => {
    const { action } = req.params;
    const site = await loadSite(req.params.id);
    if (!site || !ACTIONS.includes(action)) return notFound(res);
    let releases = { theme: [], parent: [] };
    let releaseError = null;
    if (action !== 'live') {
      try {
        releases = await listReleases(site.client_slug);
      } catch (e) {
        console.error(`Releases ophalen mislukt: ${e.message}`);
        releaseError = 'De releases konden niet worden opgehaald; alleen "nieuwste" is te kiezen.';
      }
    }
    const envNames = buildEnvNames(action, { ...site, db_pass_enc: site.has_db_pass, smtp_pass_enc: site.has_smtp_pass });
    render(res, 'run-form', {
      title: `${res.app.locals.ACTION_LABEL[action]} · ${site.site_title}`, site, action, releases, releaseError, envNames,
      installed: await installed(site.id), live: await isLive(site.id), busy: isBusy(site.id),
    });
  });

  app.post('/sites/:id/run/:action', async (req, res) => {
    const { action } = req.params;
    const site = /^\d+$/.test(req.params.id) && (await pool.query('SELECT * FROM sites WHERE id = $1', [req.params.id])).rows[0];
    if (!site || !ACTIONS.includes(action)) return notFound(res);
    const body = req.body ?? {};
    const str = (k) => (typeof body[k] === 'string' ? body[k].trim() : '');
    const block = site.theme_type !== 'bricks';
    let options;

    const confirmFlag = { deploy: 'overwrite', live: 'force' }[action];
    const flags = ['overwrite', 'force'].filter((k) => str(k));
    if (flags.length || str('retry_of')) {
      // --overwrite / --force only as the explicit confirmation of this site's latest exit-3 run.
      const prev = confirmFlag && await lastRun(site.id, [action]);
      const ok = prev && prev.status === 'needs_confirmation' && str('retry_of') === String(prev.id)
        && flags.length === 1 && flags[0] === confirmFlag && str(confirmFlag) === '1';
      if (!ok) return unprocessable(res, 'Deze bevestiging hoort niet bij de laatste run die op bevestiging wacht.');
      options = { ...prev.options, [confirmFlag]: true, retry_of: prev.id };
    } else if (action === 'live') {
      options = {};
    } else {
      const version = str('version');
      const parentVersion = block ? str('parent_version') : '';
      if (version || parentVersion) {
        let rel;
        try {
          rel = await listReleases(site.client_slug);
        } catch {
          return unprocessable(res, 'De releases konden niet worden gecontroleerd; probeer opnieuw of kies "nieuwste".');
        }
        if ((version && !rel.theme.includes(version)) || (parentVersion && !rel.parent.includes(parentVersion)))
          return unprocessable(res, 'Onbekende versie gekozen.');
      }
      options = {};
      if (version) options.version = version;
      if (parentVersion) options.parent_version = parentVersion;
      if (action === 'deploy') options.smtp = block && !!site.smtp_host;
      if (action === 'update') {
        options.apply_smtp = block && !!site.smtp_host && str('apply_smtp') === '1';
        const inst = await installed(site.id);
        options.rollback = { theme: isRollback(version, inst.theme), parent: isRollback(parentVersion, inst.parent) };
      }
    }

    const secrets = {};
    try {
      for (const name of buildEnvNames(action, site, options)) {
        secrets[name] = name === 'BRICKS_LICENSE_KEY' ? config.bricksLicenseKey
          : decrypt(site[name === 'WP_DB_PASS' ? 'db_pass_enc' : 'smtp_pass_enc'], config.encryptionKey);
      }
    } catch {
      return res.status(500).type('text').send('Kan een opgeslagen geheim niet ontsleutelen — klopt ENCRYPTION_KEY?');
    }
    try {
      const runId = await startRun(site, action, options, secrets);
      res.redirect(`/sites/${site.id}/runs/${runId}`);
    } catch (e) {
      if (e.busy) return res.status(409).type('text').send(e.message);
      throw e;
    }
  });

  async function loadRun(req) {
    const { id, runId } = req.params;
    if (!/^\d+$/.test(id) || !/^\d+$/.test(runId)) return null;
    const { rows } = await pool.query('SELECT * FROM runs WHERE id = $1 AND site_id = $2', [runId, id]);
    return rows[0] ?? null;
  }

  app.get('/sites/:id/runs/:runId.json', async (req, res) => {
    const run = await loadRun(req);
    if (!run) return res.status(404).json({ error: 'Niet gevonden.' });
    res.json({ status: run.status, log: run.log, exit_code: run.exit_code, result: run.result });
  });

  app.get('/sites/:id/runs/:runId', async (req, res) => {
    const run = await loadRun(req);
    const site = run && await loadSite(req.params.id);
    if (!site) return notFound(res);
    const canConfirm = run.status === 'needs_confirmation' && (await lastRun(site.id, [run.action]))?.id === run.id;
    render(res, 'run', { title: `Run #${run.id} · ${site.site_title}`, site, run, canConfirm });
  });

  const notFound = (res) => res.status(404).type('text').send('Niet gevonden.');
  app.use((req, res) => notFound(res));

  // Log the message only: never request bodies (they may hold secrets).
  app.use((err, req, res, next) => {
    console.error(`Fout bij ${req.method} ${req.path}: ${err.message}`);
    if (res.headersSent) return next(err);
    res.status(500).type('text').send('Er ging iets mis.');
  });

  return app;
}

function pick(obj, keys) {
  return Object.fromEntries(keys.filter((k) => typeof obj[k] === 'string').map((k) => [k, obj[k]]));
}
